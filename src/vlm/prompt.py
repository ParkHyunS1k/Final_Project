"""VLM 판정 계약 — 프롬프트·파싱·알람 규칙을 한 곳에 둔다.

**여기가 유일한 정의여야 한다.** 파인튜닝을 붙이면 학습 타깃과 평가 입력이
같은 프롬프트를 써야 하는데, 스크립트마다 프롬프트를 복사해 두면 갈라진다.
`scripts/vlm_zeroshot.py` 와 앞으로의 SFT 코드가 모두 이 모듈을 쓴다.

**채점 요소는 상부 난간대·중간 난간대 둘뿐이다** (`train_results.md` 1.9).
난간기둥은 정상·미설치 양쪽에 있고 발끝막이판은 양쪽 다 없다 — 상수를 채점하면
정확도만 부푼다. 난간기둥·발끝막이판은 리포트 표시용이다.

**알람 규칙은 상부 난간대 하나로 정한다** (`eval_protocol.md` 3.2).
제13조의 필수 요소이고, 파일럿에서 중간 난간대는 272구역 중 259개가
`판정불가`였다 (`train_results.md` 1.10).
"""

from __future__ import annotations

import re

VALUES = ("있음", "없음", "판정불가")

GUARDRAIL_BINARY = """이 사진은 건설현장 비계의 작업발판 한 칸이다. 안전난간을 판정하라.

- 상부 난간대: 작업발판에서 약 90cm 높이에 가로로 설치된 난간대
- 중간 난간대: 상부 난간대와 발판 사이 중간 높이의 가로 난간대

비계를 지탱하는 구조재나 대각선 가새는 난간대가 아니다.
가려지거나 화질 때문에 확신할 수 없으면 "판정불가" 로 답하라.

각각 "있음" / "없음" / "판정불가" 중 하나로만 답하고, JSON 만 출력하라.
{"상부난간대": "...", "중간난간대": "..."}"""


def parse(text: str) -> tuple[str, str]:
    """모델 출력에서 두 요소를 뽑는다. 못 뽑으면 판정불가로 센다."""
    def one(key: str) -> str:
        m = re.search(rf'"{key}"\s*:\s*"([^"]*)"', text)
        v = m.group(1).strip() if m else ""
        return v if v in VALUES else "판정불가"
    return one("상부난간대"), one("중간난간대")


def alarm(top: str, mid: str) -> bool | None:
    """미설치 알람 여부. None 은 기권이다.

    `mid` 는 받아 두되 쓰지 않는다 — 민감도 분석용이다. 규칙을 바꾸려면
    `eval_protocol.md` 3.2 를 먼저 고칠 것. **결과를 보고 바꾸지 않는다.**
    """
    return None if top == "판정불가" else (top == "없음")
